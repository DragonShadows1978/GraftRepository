def fires(masses, mounted, reg):
    return {k: v["fire"] for k, v in c3.decisions(masses, mounted, reg["rules"]).items()}


def test_hand_computed_trace_table(reg):
    # These expected bits are literal hand calculations, NOT generated by
    # the code under test: min .32 separates carried/candidate, .30 separates
    # candidate/near-zero, tiny nonempty separates near-zero/empty-band.
    samples = [([.7, .4], 12, [False, False, False, False]),
               ([.6, .32], 12, [True, False, False, False]),
               ([.4, .30], 12, [True, True, False, False]),
               ([.5, 1e-9], 12, [True, True, True, False]),
               ([0., 0.], 0, [True, True, True, True]),
               ([0.], 12, [True, True, True, False])]
    for masses, mounted, expected in samples:
        got = c3.decisions(masses, mounted, reg["rules"])
        assert [got[n]["fire"] for n in ["carried", "candidate", "near_zero", "empty_band"]] == expected
    assert c3.decisions([.6, .32, .1], 12, reg["rules"])["carried"]["first_index"] == 1
    assert c3.decisions([.6, .32, .1], 12, reg["rules"])["candidate"]["first_index"] == 2


@pytest.mark.parametrize("rule", ["carried", "candidate", "near_zero"])
def test_strict_exact_boundary(reg, rule):
    t = reg["rules"][rule]["threshold"]
    assert not c3.decisions([t], 12, reg["rules"])[rule]["fire"]
    assert c3.decisions([math.nextafter(t, 0.)], 12, reg["rules"])[rule]["fire"]
    assert not c3.decisions([math.nextafter(t, 1.)], 12, reg["rules"])[rule]["fire"]


